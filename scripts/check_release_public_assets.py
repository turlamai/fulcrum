#!/usr/bin/env python3
"""Fail-closed inventory and checksum gate for public Fulcrum release assets.

The signed updater feeds are kept for both current and legacy clients.
Individual .sha256 sidecars and unrelated build output remain CI-only.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

FIXED_SUFFIXES = (
    "macos-arm64.dmg", "macos-arm64.zip",
    "macos-x64.dmg", "macos-x64.zip",
    "windows-x64.msi", "windows-x64.zip",
    "linux-arm64.zip", "linux-x64.zip",
    "linux-amd64.deb", "linux-arm64.deb",
    "linux-x86_64.AppImage", "linux-aarch64.AppImage",
    "linux-x64.tar.gz", "linux-arm64.tar.gz",
    "linux-x64.tar.gz.sig", "linux-arm64.tar.gz.sig",
)
RPM_ARCHES = ("x86_64", "aarch64")
UPDATE_FEEDS = ("update-manifest.json", "manifest.json")
VERSION_PATTERN = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+")


def verify_inventory(directory: Path, version: str) -> list[Path]:
    if not VERSION_PATTERN.fullmatch(version):
        raise ValueError(f"Expected a stable SemVer base version: {version!r}")
    if not directory.is_dir():
        raise ValueError(f"Public staging directory does not exist: {directory}")

    staged = {path.name: path for path in directory.iterdir()}
    expected = {f"fulcrum-{version}-{suffix}" for suffix in FIXED_SUFFIXES}
    expected.update(UPDATE_FEEDS)

    for arch in RPM_ARCHES:
        # The RPM package revision is separate from the app version.
        pattern = re.compile(
            rf"fulcrum-{re.escape(version)}-[0-9]+-linux-{arch}\.rpm"
        )
        matches = sorted(name for name in staged if pattern.fullmatch(name))
        if len(matches) != 1:
            raise ValueError(
                f"Expected exactly one versioned RPM for {arch}: found {matches}"
            )
        expected.add(matches[0])

    # SHA256SUMS is generated by this gate, never taken from an earlier step.
    actual = set(staged) - {"SHA256SUMS"}
    if actual != expected:
        raise ValueError(
            f"Unexpected public asset inventory; "
            f"missing={sorted(expected - actual)}, extra={sorted(actual - expected)}"
        )

    for name in sorted(expected):
        path = staged[name]
        if path.is_symlink() or not path.is_file() or path.stat().st_size == 0:
            raise ValueError(f"Empty, invalid, or symlinked release asset: {name}")

    # The legacy feed name must resolve to precisely the same signed bytes.
    if (directory / UPDATE_FEEDS[0]).read_bytes() != (
        directory / UPDATE_FEEDS[1]
    ).read_bytes():
        raise ValueError("Legacy and canonical signed update feeds differ")

    return [staged[name] for name in sorted(expected)]


def write_checksums(directory: Path, version: str) -> Path:
    files = verify_inventory(directory, version)
    lines = []
    for path in files:
        digest = hashlib.sha256()
        with path.open("rb") as source:
            for chunk in iter(lambda: source.read(1024 * 1024), b""):
                digest.update(chunk)
        lines.append(f"{digest.hexdigest()}  {path.name}\n")
    target = directory / "SHA256SUMS"
    target.write_text("".join(lines), encoding="utf-8")
    return target


def main() -> int:
    if len(sys.argv) != 3:
        print(
            "usage: check_release_public_assets.py VERSION STAGING_DIR",
            file=sys.stderr,
        )
        return 2
    try:
        manifest = write_checksums(Path(sys.argv[2]), sys.argv[1])
    except (OSError, ValueError) as exc:
        print(f"release-assets: {exc}", file=sys.stderr)
        return 1
    print(f"release-assets: verified 18 packages + 2 signed feed names: {manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
